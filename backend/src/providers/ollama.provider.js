import BaseProvider from './base.provider.js';
import config from '../config/index.js';

/**
 * Ollama Local VLM Provider Adapter
 */
export class OllamaProvider extends BaseProvider {
  constructor() {
    super({ name: 'ollama' });
  }

  /**
   * Helper checking if local Ollama base URL is configured
   */
  isConfigured() {
    return Boolean(config.ollamaBaseUrl && config.ollamaBaseUrl.trim().length > 0);
  }

  /**
   * Calls local Ollama vision model API
   */
  async analyze({ prompt, imagePaths = [], task, modelName }) {
    const selectedModel = modelName || config.ollamaModel || 'qwen2-vl';
    const baseUrl = config.ollamaBaseUrl.replace(/\/+$/, '');

    // Convert image paths to raw base64 string array
    const rawImages = imagePaths.map(imgPath => this.imageToRawBase64(imgPath));

    const payload = {
      model: selectedModel,
      prompt,
      images: rawImages,
      stream: false,
      options: {
        temperature: 0.2
      }
    };

    try {
      const response = await this.fetchWithTimeout(`${baseUrl}/api/generate`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json'
        },
        body: JSON.stringify(payload)
      });

      const data = await response.json();

      if (!response.ok) {
        const errMsg = data.error || `Ollama API returned HTTP status ${response.status}`;
        const err = new Error(`Ollama VLM Provider failure: ${errMsg}`);
        err.code = 'OLLAMA_API_ERROR';
        throw err;
      }

      const answerText = data.response || 'No response generated by Ollama VLM.';

      return {
        answerText: answerText.trim(),
        confidence: null, // Generic VLMs do not output calibrated confidence scores
        parametersUsed: {
          model: selectedModel,
          provider: 'ollama',
          temperature: 0.2,
          imagesProcessed: imagePaths.length
        },
        warnings: []
      };
    } catch (error) {
      if (error.code === 'VLM_TIMEOUT' || error.code === 'OLLAMA_API_ERROR') {
        throw error;
      }
      const connErr = new Error(`Ollama VLM Provider unavailable at ${baseUrl}: ${error.message}`);
      connErr.code = 'OLLAMA_UNAVAILABLE';
      throw connErr;
    }
  }
}

export const ollamaProvider = new OllamaProvider();
export default ollamaProvider;
